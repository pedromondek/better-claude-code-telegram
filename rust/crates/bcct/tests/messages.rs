fn fixture() -> Value {
    serde_json::from_str(FIXTURE).unwrap_or(Value::Null)
}

fn locale_entries(fixture: &Value, locale: Locale) -> Option<&serde_json::Map<String, Value>> {
    fixture.get(locale.as_str()).and_then(Value::as_object)
}

#[test]
fn every_fixture_entry_renders_byte_identical_to_the_js_catalog() {
    let fixture = fixture();

    for locale in Locale::ALL {
        let messages = messages_for(locale);

        for (key, entry) in locale_entries(&fixture, locale).unwrap() {
            match entry {
                Value::String(expected) => {
                    assert_eq!(
                        render(messages, key, &[]).as_deref(),
                        Some(expected.as_str()),
                        "{} {key}",
                        locale.as_str()
                    );
                }
                Value::Array(calls) => {
                    assert!(!calls.is_empty(), "{} {key}", locale.as_str());
                    for call in calls {
                        let args = call
                            .get("args")
                            .and_then(Value::as_array)
                            .unwrap()
                            .as_slice();
                        let expected = call.get("out").and_then(Value::as_str).unwrap();
                        assert_eq!(
                            render(messages, key, args).as_deref(),
                            Some(expected),
                            "{} {key} {args:?}",
                            locale.as_str()
                        );
                    }
                }
                other => panic!("unexpected fixture entry for {key}: {other:?}"),
            }
        }
    }
}

#[test]
fn the_fixture_covers_every_catalog_key_in_both_locales() {
    let fixture = fixture();
    let catalog: BTreeSet<&str> = KEYS.iter().copied().collect();

    assert_eq!(catalog.len(), KEYS.len());

    for locale in Locale::ALL {
        let recorded: BTreeSet<&str> = locale_entries(&fixture, locale)
            .unwrap()
            .keys()
            .map(String::as_str)
            .collect();

        assert_eq!(recorded, catalog, "{}", locale.as_str());
    }
}

#[test]
fn an_unknown_key_renders_nothing() {
    assert_eq!(render(messages_for(Locale::EnUs), "nope", &[]), None);
}

#[test]
fn both_locales_resolve_to_their_own_catalog() {
    assert_eq!(messages_for(Locale::EnUs).yes, "Yes");
    assert_eq!(messages_for(Locale::PtBr).yes, "Sim");
}
